test('guest: real Steam entry, English/Russian persistence and mobile layout', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('link', { name: 'Sign in with Steam' })).toHaveAttribute('href', '/api/auth/steam');
  await expect(page.locator('.guest-hero')).toBeVisible();
  await expect.poll(() => page.locator('.guest-hero').evaluate((image: HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0);
  await page.screenshot({ path: 'test-results/guest-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'RU', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Войти через Steam' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('link', { name: 'Войти через Steam' })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('html')).toHaveAttribute('lang', 'ru');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/guest-mobile-ru.png', fullPage: true });
  expect(errors).toEqual([]);
});
