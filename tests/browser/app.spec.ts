test('mobile filter expansion, touch swipe and recoverable discovery error', async ({ page, context }) => {
  await context.addCookies([{ name: 'session', value: 'e2e-viewer', url: 'http://localhost:3100' }]);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Nightjar', exact: true })).toBeVisible();
  const filters = page.getByRole('button', { name: 'Fine-tune your search' });
  await expect(filters).toHaveAttribute('aria-expanded', 'false');
  await filters.click();
  await expect(page.getByRole('button', { name: 'Apply filters' })).toBeVisible();
  await filters.click();
  await page.locator('.player-card').evaluate(element => {
    const start = new Touch({ identifier: 1, target: element, clientX: 40, clientY: 400 });
    const end = new Touch({ identifier: 1, target: element, clientX: 200, clientY: 410 });
    element.dispatchEvent(new TouchEvent('touchstart', { bubbles: true, touches: [start] }));
    element.dispatchEvent(new TouchEvent('touchend', { bubbles: true, changedTouches: [end] }));
  });
  await expect(page.getByRole('status').filter({ hasText: 'Like saved' })).toBeVisible();
  await page.route('**/api/discovery', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'unavailable' }) }));
  await page.reload();
  await expect(page.locator('.notice[role="alert"]')).toContainText('temporarily unavailable');
  await page.unroute('**/api/discovery');
  await page.getByRole('button', { name: 'Try again' }).click();
  await expect(page.getByRole('heading', { name: 'You’ve reached the end of the deck' })).toBeVisible();
});
