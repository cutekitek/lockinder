test('rank slider supports dragging, keyboard bounds, persistence and reset', async ({ page, context }) => {
  await context.addCookies([{ name: 'session', value: 'e2e-viewer', url: 'http://localhost:3100' }]);
  await page.goto('/');
  const min = page.getByRole('slider', { name: 'Minimum rank' });
  const max = page.getByRole('slider', { name: 'Maximum rank' });
  await expect(min).toHaveValue('0');
  await expect(max).toHaveValue('65');
  const box = (await min.boundingBox())!;
  await page.mouse.move(box.x + 22, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 3, box.y + box.height / 2, { steps: 8 });
  await page.mouse.up();
  expect(Number(await min.inputValue())).toBeGreaterThan(0);
  await min.focus(); await page.keyboard.press('Home'); await page.keyboard.press('ArrowRight');
  await max.focus(); await page.keyboard.press('End'); await page.keyboard.press('ArrowLeft');
  await page.getByRole('button', { name: 'Apply filters' }).click();
  await page.reload();
  await expect(min).toHaveValue('1'); await expect(max).toHaveValue('64');
  await min.focus(); await page.keyboard.press('End');
  await expect(min).toHaveValue('64');
  await max.focus(); await page.keyboard.press('Home');
  await expect(max).toHaveValue('64');
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  await expect(min).toHaveValue('0'); await expect(max).toHaveValue('65');
  await page.screenshot({ path: 'test-results/rank-slider-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Fine-tune your search' }).click();
  await expect(min).toBeVisible();
  await page.screenshot({ path: 'test-results/rank-slider-mobile.png', fullPage: true });
});

